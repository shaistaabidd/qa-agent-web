function money(value: number | null | undefined) {
  return `$${value ?? 0}`;
}

export function serviceTypeDescription(serviceType: string | null | undefined) {
  if (serviceType === 'function_rx_service') {
    return 'FunctionRx team generates sequences for the practitioners. Practitioners cannot create their own sequences. This cannot be changed.';
  }

  return 'Practitioners can create their own sequences and even ask for FunctionRx help. This cannot be changed.';
}

