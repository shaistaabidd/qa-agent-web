function frontEndBaseUrl() {
  return import.meta.env.VITE_REDIRECT_FRONTND_URL || window.location.origin;
}

function numberParam(params: URLSearchParams, key: string) {
  const value = params.get(key);
  if (value == null || value === '') {
    return null;
  }

  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : null;
}

export function clinicBillingFromSearchParams(params: URLSearchParams): ClinicBilling {
  return {
    additionalSequencePrice: numberParam(params, 'additionalSequencePrice'),
    additionalSequencePriceForFunctionRx: numberParam(
      params,
      'additionalSequencePriceForFunctionRx',
    ),
    additionalSequencePriceForPractitioners: numberParam(
      params,
      'additionalSequencePriceForPractitioners',
    ),
    assessmentPrice: numberParam(params, 'assessmentPrice'),
    basePrice: numberParam(params, 'basePrice'),
    maxSequenceLimit: numberParam(params, 'maxSequenceLimit'),
    revaluationPrice: numberParam(params, 'revaluationPrice'),
    serviceType: params.get('serviceType'),
    submittedAssessmentPrice: numberParam(params, 'submittedAssessmentPrice'),
    virtualTherapyAppointmentPricing: numberParam(params, 'virtualTherapyAppointmentPricing'),
  };
}

export function buildPaymentUrls(clinic: ClinicBilling) {
  const params = new URLSearchParams({
    serviceType: clinic.serviceType ?? '',
    basePrice: String(clinic.basePrice ?? 0),
    virtualTherapyAppointmentPricing: String(clinic.virtualTherapyAppointmentPricing ?? 0),
  });

  if (clinic.serviceType === 'function_rx_service') {
    params.set('assessmentPrice', String(clinic.assessmentPrice ?? 0));
    params.set('additionalSequencePrice', String(clinic.additionalSequencePrice ?? 0));
    params.set('revaluationPrice', String(clinic.revaluationPrice ?? 0));
  } else {
    params.set('maxSequenceLimit', String(clinic.maxSequenceLimit ?? 0));
    params.set(
      'additionalSequencePriceForPractitioners',
      String(clinic.additionalSequencePriceForPractitioners ?? 0),
    );
    params.set('submittedAssessmentPrice', String(clinic.submittedAssessmentPrice ?? 0));
    params.set(
      'additionalSequencePriceForFunctionRx',
      String(clinic.additionalSequencePriceForFunctionRx ?? 0),
    );
  }

  const query = params.toString();
  const base = frontEndBaseUrl();

  return {
    successUrl: `${base}${SETUP_PATHS.paymentSuccess}?${query}`,
    cancelUrl: `${base}${SETUP_PATHS.paymentFailed}?${query}`,
  };
}
